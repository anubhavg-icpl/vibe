#!/usr/bin/env node
/**
 * Generates two artifacts for the system-prompts/ reference collection:
 *   1. system-prompts/INDEX.md   — human-readable index, grouped by vendor.
 *   2. system-prompts/index.json — machine manifest the VIBE CLI reads so the
 *      758-file collection is installable/searchable without walking the tree.
 *
 * No external dependencies (node:fs + node:path only).
 *
 * Run:  npm run build:system-prompts
 */

import { readdirSync, statSync, writeFileSync, readFileSync } from "node:fs";
import { join, basename, relative, sep, posix, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const PROMPTS_DIR = join(ROOT, "system-prompts");

// Meta files to exclude anywhere in the tree.
const SKIP_FILES = new Set([
  "README.md",
  "INDEX.md",
  "UPSTREAM-asgeirtj-README.md",
]);

/** Repo-root-relative, forward-slash separated. */
const fwdRel = (abs) => relative(ROOT, abs).split(sep).join(posix.sep);

/** Recursively collect *.md files (excluding meta files). */
function walk(dir, out) {
  for (const name of readdirSync(dir)) {
    const abs = join(dir, name);
    const info = statSync(abs);
    if (info.isDirectory()) {
      walk(abs, out);
    } else if (name.endsWith(".md") && !SKIP_FILES.has(name)) {
      out.push({ abs, sizeKB: info.size / 1024 });
    }
  }
  return out;
}

/** URL-encode spaces in a forward-slash path so GitHub links resolve. */
const encodeLink = (relPath) => relPath.replace(/ /g, "%20");

/** First meaningful line of a prompt → a short, one-line description. */
function firstLineDescription(abs) {
  let raw;
  try {
    raw = readFileSync(abs, "utf-8");
  } catch {
    return "Reference system prompt.";
  }
  for (const line of raw.split("\n")) {
    const t = line.trim();
    if (t.length >= 12 && !t.startsWith("#") && !t.startsWith("---") && !t.startsWith("<!--") && !t.startsWith(">")) {
      return t.length > 160 ? t.slice(0, 157) + "…" : t;
    }
  }
  return "Reference system prompt.";
}

function main() {
  const files = walk(PROMPTS_DIR, []);

  // Group by top-level directory under system-prompts/.
  const byVendor = new Map();
  for (const f of files) {
    const rel = fwdRel(f.abs); // e.g. system-prompts/Anthropic/foo.md
    const parts = rel.split("/");
    const vendor = parts[1]; // segment after "system-prompts"
    if (!byVendor.has(vendor)) byVendor.set(vendor, []);
    byVendor.get(vendor).push({
      rel,
      name: basename(f.abs),
      sizeKB: f.sizeKB,
    });
  }

  const vendors = [...byVendor.keys()].sort((a, b) => a.localeCompare(b));
  for (const v of vendors) {
    byVendor.get(v).sort((a, b) => a.rel.localeCompare(b.rel));
  }

  const totalFiles = files.length;

  // ── Machine manifest (system-prompts/index.json) ──────────────────────────
  // Stable, unique `name` per prompt (basename; vendor-prefixed on collision)
  // so `vibe add <name>` is deterministic. `category` is the vendor folder.
  const seenNames = new Set();
  const manifestPrompts = [];
  for (const v of vendors) {
    for (const f of byVendor.get(v)) {
      const base = f.name.replace(/\.md$/, "");
      let name = base;
      if (seenNames.has(name.toLowerCase())) {
        name = `${v.toLowerCase().replace(/[^a-z0-9]+/g, "-")}-${base}`;
      }
      seenNames.add(name.toLowerCase());
      manifestPrompts.push({
        name,
        category: v,
        path: f.rel,
        sizeKB: Number(f.sizeKB.toFixed(1)),
        description: firstLineDescription(join(ROOT, f.rel.split("/").join(sep))),
      });
    }
  }
  manifestPrompts.sort((a, b) => a.name.localeCompare(b.name));
  const manifest = {
    version: 1,
    count: manifestPrompts.length,
    vendors: vendors.map((v) => ({ name: v, count: byVendor.get(v).length })),
    prompts: manifestPrompts,
  };
  writeFileSync(
    join(PROMPTS_DIR, "index.json"),
    JSON.stringify(manifest, null, 2) + "\n",
  );

  // Build the markdown.
  const lines = [];
  lines.push(
    "<!-- AUTO-GENERATED by scripts/build-system-prompts-index.mjs — do not edit by hand. Run: npm run build:system-prompts -->",
  );
  lines.push("");
  lines.push("# System Prompts — Index");
  lines.push("");
  lines.push(
    "A reference collection of leaked and published system prompts, grouped by vendor / source.",
  );
  lines.push("");
  lines.push(`**Total files:** ${totalFiles} across ${vendors.length} vendors`);
  lines.push("");
  lines.push("| Vendor | Files |");
  lines.push("| --- | --- |");
  for (const v of vendors) {
    lines.push(`| ${v} | ${byVendor.get(v).length} |`);
  }
  lines.push("");

  for (const v of vendors) {
    lines.push(`## ${v}`);
    lines.push("");
    for (const f of byVendor.get(v)) {
      lines.push(
        `- [${f.name}](${encodeLink(f.rel)}) — ${f.sizeKB.toFixed(1)} KB`,
      );
    }
    lines.push("");
  }

  writeFileSync(join(PROMPTS_DIR, "INDEX.md"), lines.join("\n"));

  console.log(
    `Wrote system-prompts/INDEX.md + index.json — ${totalFiles} files across ${vendors.length} vendors.`,
  );
}

try {
  main();
} catch (err) {
  console.error("build-system-prompts-index failed:", err);
  process.exit(1);
}
